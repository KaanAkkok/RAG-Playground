from pydantic import BaseModel, Field

from rag_playground.models.vector_model import VectorRecord
from rag_playground.schemas.intent_schema import Intent


class AssistantResponse(BaseModel):
    answer: str = Field(..., description="The answer generated by the assistant.")
    intent: Intent = Field(..., description="The intent of the assistant's response.")
    citations: list[VectorRecord] = Field(
        default_factory=list,
        description="List of citations used to generate the answer.",
    )
